(async () => {
  const results = [];
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
  const check = (name, condition) => { results.push({ name, passed:!!condition }); if (!condition) throw new Error(name); };
  const until = async selector => { for(let i=0;i<250;i++){ if(document.querySelector(selector)) return; await pause(20); } throw new Error('timeout: '+selector); };
  const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  try {
    while (!db && !memMode) await pause(20);
    await renderLib();
    document.querySelector('#btnAdd').focus();
    openImportSheet(); await frame();
    check('dialog focuses close control', document.activeElement.id === 'sheetX');
    check('background is hidden during dialog', document.querySelector('#vLib').getAttribute('aria-hidden') === 'true');
    document.querySelector('#sheetX').dispatchEvent(new KeyboardEvent('keydown',{key:'Tab',shiftKey:true,bubbles:true,cancelable:true}));
    check('Shift+Tab wraps to last action', document.activeElement.id === 'imZip');
    document.querySelector('#imZip').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));
    check('Escape closes and restores focus', !document.querySelector('#sheet.on') && document.activeElement.id === 'btnAdd');
    for (let i=0;i<12;i++) { openImportSheet(); closeSheet(); }
    await frame();
    check('rapid open/close leaves no stale focus', document.activeElement.id === 'btnAdd' && !document.querySelector('#sheet.on') && !document.querySelector('#vLib').hasAttribute('aria-hidden'));
    let answer = confirmAction({title:'测试确认',message:'仅用于隔离交互测试',action:'确定'});
    document.querySelector('#sheet').click();
    check('backdrop cancellation resolves false', await answer === false);
    answer = confirmAction({title:'测试确认',message:'仅用于隔离交互测试',action:'确定'});
    document.querySelector('#sheetX').click();
    check('native-back close target cancels confirmation', await answer === false);
    answer = confirmAction({title:'测试确认',message:'仅用于隔离交互测试',action:'确定'});
    document.querySelector('#confirmAccept').click();
    check('explicit confirmation resolves true', await answer === true);
    cur = { id:'ui-translation-only', tr:{0:'保留的测试译文'} };
    cues = [{s:0,e:1,en:'Translation cancel test.'}];
    openSheet();
    document.querySelector('#optRe').click();
    document.querySelector('#confirmCancel').click(); await frame();
    check('retranslation cancellation preserves translations', cur.tr[0] === '保留的测试译文' && !translating);
    cur = null; cues = []; // Do not let pagehide save the temporary translation stub.
    await dbDel('ui-translation-only');
    const restoreTrack = {id:'ui-restore-regression',name:'自动恢复临时材料',createdAt:2,blob:new Blob([new Uint8Array(44)],{type:'audio/wav'}),cues:[],progress:0};
    const backup = await makeBackup([restoreTrack]);
    const chooseBackup = () => { const transfer = new DataTransfer(); transfer.items.add(new File([backup],'ui-regression.jtbak')); backupInput.files = transfer.files; };
    chooseBackup();
    let restoreDone = backupInput.onchange();
    await until('#sheet.on #confirmCancel');
    document.querySelector('#confirmCancel').click(); await restoreDone;
    check('restore cancellation writes no material and clears busy state', !(await dbAll()).some(t=>t.id===restoreTrack.id) && !backupBusy);
    chooseBackup();
    restoreDone = backupInput.onchange();
    await until('#sheet.on #confirmAccept');
    document.querySelector('#confirmAccept').click(); await restoreDone;
    check('restore confirmation restores exactly one material', (await dbAll()).filter(t=>t.id===restoreTrack.id).length===1 && !backupBusy);
    chooseBackup();
    restoreDone = backupInput.onchange();
    await until('#sheet.on #confirmAccept');
    check('restore duplicate confirmation reports skipped material', document.querySelector('.confirm-message').textContent.includes('1 条已存在将跳过'));
    document.querySelector('#confirmAccept').click(); await restoreDone;
    check('duplicate restore creates no duplicate', (await dbAll()).filter(t=>t.id===restoreTrack.id).length===1);
    await dbDel(restoreTrack.id); await renderLib();
    const id='ui-regression-only';
    await dbPut({id,name:'自动回归临时材料',createdAt:1,blob:new Blob([new Uint8Array(44)],{type:'audio/wav'}),cues:[],progress:0});
    await renderLib();
    const open = [...document.querySelectorAll('.row')].find(el=>el.dataset.id===id).querySelector('.track-open');
    open.dispatchEvent(new PointerEvent('pointerdown',{pointerType:'touch',isPrimary:true,bubbles:true}));
    await pause(700);
    open.dispatchEvent(new PointerEvent('pointerup',{pointerType:'touch',isPrimary:true,bubbles:true}));
    open.dispatchEvent(new MouseEvent('click',{bubbles:true,detail:1,cancelable:true}));
    check('touch long press opens actions without opening track', document.querySelector('#sheetTitle').textContent==='材料操作' && document.querySelector('#vLib.on') && !document.querySelector('#vPlay.on'));
    closeSheet();
    open.dispatchEvent(new PointerEvent('pointerdown',{pointerType:'touch',isPrimary:true,bubbles:true}));
    open.dispatchEvent(new PointerEvent('pointercancel',{pointerType:'touch',isPrimary:true,bubbles:true}));
    await pause(700);
    check('cancelled touch does not open actions', !document.querySelector('#sheet.on'));
    await dbDel(id); await renderLib();
  } catch(error) { results.push({name:'failure: '+error.message,passed:false}); }
  const report=document.createElement('pre');report.id='testReport';report.textContent=JSON.stringify(results,null,2);
  report.style.cssText='position:fixed;inset:8px;z-index:9999;overflow:auto;background:#1c1c1e;color:#fff;padding:16px;white-space:pre-wrap;';
  document.body.appendChild(report);
  document.title='交互回归 '+results.filter(r=>r.passed).length+'/'+results.length;
})();
